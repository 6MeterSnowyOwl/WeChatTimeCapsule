class AcceptanceSession:
    """Borrowed memory lease; identity/count policy remains real."""
    def __init__(self, inventory):
        self.inventory = inventory
        self.closed = False
        self.raw_reads = 0

    def assert_source_set_stable(self):
        pass

    def close(self):
        self.closed = True

    def resolve_raw_row(self, token):
        self.raw_reads += 1
        raise AssertionError("UNEXPECTED_RAW_READ")


class UnusedRoot:
    def __init__(self):
        self.accesses = 0

    def __fspath__(self):
        self.accesses += 1
        raise AssertionError("UNEXPECTED_ROOT_ACCESS")


