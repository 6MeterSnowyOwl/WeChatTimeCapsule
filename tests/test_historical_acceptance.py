    def test_combined_committed_hash_rejection_preserves_transaction_evidence(self):
        # Wrong committed bytes must block cleanup before semantic callback.
        with synthetic_acceptance_history() as f:
            assets = self.asset_snapshot(f)
            target, stage, names, hashes, verify = self.transaction_markers(f)
            prepared = tx.prepare_synthetic_transaction(target, stage, names, hashes, verify_postimage=verify)
            tx.commit_synthetic_transaction(prepared, before_install=lambda: None)
            (target / names[0]).write_bytes(b"synthetic tampered marker")
            metadata = target / ".synthetic-transaction"
            evidence = {p.name: p.read_bytes() for p in metadata.iterdir() if p.is_file()}
            with self.assertRaises(HistoryError) as caught:
                tx.recover_synthetic_transaction(target, verify_postimage=verify)
            self.assertEqual(caught.exception.code, "TRANSACTION_RECOVERY_REQUIRED")
            self.assertEqual({p.name: p.read_bytes() for p in metadata.iterdir() if p.is_file()}, evidence)
            self.assertEqual((target / names[0]).read_bytes(), b"synthetic tampered marker")
            self.assertEqual(self.asset_snapshot(f), assets)


