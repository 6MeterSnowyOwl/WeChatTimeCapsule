    def transaction_markers(self, fixture):
        """Generic acceptance markers, explicitly not a v3 serialized save."""
        with fixture.reader.open_inventory(mode="full") as session:
            counts = self.collect(fixture.legacy, session).counts
        target, stage = fixture.root / "marker-target", fixture.root / "marker-stage"
        target.mkdir()
        stage.mkdir()
        names = ("acceptance-counts.txt", "acceptance-complete.txt")
        payload = (f"union={counts.final_union_count}\nnew={counts.newly_discovered_count}\n"
                   f"first={counts.earliest_timestamp}\nlast={counts.latest_timestamp}\n").encode()
        self.assertEqual(payload, b"union=5\nnew=2\nfirst=10\nlast=50\n")
        (target / names[0]).write_bytes(b"synthetic prior marker")
        (stage / names[0]).write_bytes(payload)
        (stage / names[1]).write_bytes(b"")
        hashes = {names[0]: hashlib.sha256(payload).hexdigest(), names[1]: hashlib.sha256(b"").hexdigest()}
        def verify(root):
            # Read-only semantic callback; caller excludes concurrent writers.
            self.assertEqual((root / names[0]).read_bytes(), b"union=5\nnew=2\nfirst=10\nlast=50\n")
            self.assertEqual((root / names[1]).read_bytes(), b"")
        return target, stage, names, hashes, verify

    def test_collection_generic_markers_commit_and_verified_cleanup(self):
        # Catches collection/transaction mismatch and premature cleanup.
        with synthetic_acceptance_history() as f:
            assets = self.asset_snapshot(f)
            target, stage, names, hashes, verify = self.transaction_markers(f)
            staged = tuple((stage / name).read_bytes() for name in names)
            prepared = tx.prepare_synthetic_transaction(target, stage, names, hashes, verify_postimage=verify)
            self.assertEqual((target / names[0]).read_bytes(), b"synthetic prior marker")
            self.assertFalse((target / names[1]).exists())
            tx.commit_synthetic_transaction(prepared, before_install=lambda: None)
            verify(target)
            self.assertTrue(tx.recover_synthetic_transaction(target, verify_postimage=verify))
            self.assertFalse(tx.recover_synthetic_transaction(target, verify_postimage=verify))
            self.assertEqual(tuple((stage / name).read_bytes() for name in names), staged)
            self.assertEqual(self.asset_snapshot(f), assets)

