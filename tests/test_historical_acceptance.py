    def test_actual_source_drift_retries_once_and_returns_no_raw_lease(self):
        # Only fresh second inventory may be accepted; all owned leases expire.
        with synthetic_acceptance_history() as f:
            sessions, candidates = [], []
            def opening():
                session = f.reader.open_inventory(mode="full")
                sessions.append(session)
                return session
            def observe(session, collection):
                candidates.append(collection.counts.final_union_count)
                if len(sessions) == 1:
                    self.add_shard(f, 3, 105)
            result = collect_with_retry(opening, f.legacy, mode="full",
                                        authorization=ScopeAuthorization(f.scope, True), before_accept=observe)
            self.assertEqual(candidates, [5, 6])
            self.assertEqual((len(sessions), result.counts.raw_source_count,
                              result.counts.newly_discovered_count, result.counts.final_union_count), (2, 6, 3, 6))
            for session in sessions:
                with self.assertRaises(HistoryError) as caught:
                    session.resolve_raw_row(session.inventory.rows[0].raw_row_token)
                self.assertEqual(caught.exception.code, "SOURCE_READ_FAILED")
            self.assertEqual(list(f.work.iterdir()), [])

